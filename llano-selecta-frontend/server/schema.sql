-- =========================================================================
-- Llano SELECTA Dealer POS and Inventory Database Initialization
-- All products extracted exactly from Dealer Inventory & Booking Sheet
-- =========================================================================

CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(50) PRIMARY KEY,
    barcode VARCHAR(50),
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    dealer_price NUMERIC(10, 2) NOT NULL,
    srp NUMERIC(10, 2),
    stock INT DEFAULT 50,
    min_stock INT DEFAULT 15,
    unit VARCHAR(50) DEFAULT 'Pack'
);

CREATE TABLE IF NOT EXISTS customers (
    id VARCHAR(50) PRIMARY KEY,
    store_name VARCHAR(255) NOT NULL,
    owner VARCHAR(255),
    area VARCHAR(255),
    route VARCHAR(255),
    contact VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS bookings (
    id VARCHAR(50) PRIMARY KEY,
    store_name VARCHAR(255) NOT NULL,
    booking_date DATE DEFAULT CURRENT_DATE,
    status VARCHAR(50) DEFAULT 'Booked',
    items JSONB,
    estimated_total NUMERIC(12, 2) DEFAULT 0.00,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

